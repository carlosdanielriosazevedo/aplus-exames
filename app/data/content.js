export const MICROCOMPETENCIES=Object.entries(MICROCOMPETENCY_DEFS).flatMap(([themeId,rows])=>rows.map(x=>({...x,themeId})));

export function microcompetencyFor(themeId,ref){
  if(!ref)return null;
  return (MICROCOMPETENCY_DEFS[themeId]||[]).find(
    x=>x.id===ref || x.label===ref || (x.aliases||[]).includes(ref)
  )||null;
}
export function microcompetencyId(themeId,ref){
  return microcompetencyFor(themeId,ref)?.id||null;
}
export function microcompetencyLabel(ref){
  if(!ref)return null;
  return MICROCOMPETENCIES.find(x=>x.id===ref)?.label||null;
}


