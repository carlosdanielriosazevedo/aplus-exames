export function curriculumSubtopicsForTheme(themeId){
  return CURRICULUM_SUBTOPICS.filter(row=>row.themeId===themeId);
}

export function curriculumSubtopicId(themeId,ref){
  if(!ref)return null;
  const direct=CURRICULUM_SUBTOPIC_BY_ID.get(ref);
  if(direct)return direct.themeId===themeId?direct.id:null;
  const migrated=LEGACY_MICROCOMPETENCY_SUBTOPIC[ref]||null;
  return CURRICULUM_SUBTOPIC_BY_ID.get(migrated)?.themeId===themeId?migrated:null;
}

export function curriculumSubtopicForItem(item){
  if(item?.subtopicId)return curriculumSubtopicId(item.themeId,item.subtopicId);
  const override=LEGACY_ITEM_SUBTOPIC[item?.id];
  return curriculumSubtopicId(item?.themeId,override||item?.microcompetencyId)||null;
}
